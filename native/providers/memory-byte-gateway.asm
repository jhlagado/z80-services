; Bounded in-memory byte-gateway reference provider.
; Tests initialise the exported workspace before entering the client program.

ZS_CAP   EQU 16
ZF_RIN   EQU 1
ZF_WOUT  EQU 2
ZF_RST   EQU 4
ZF_RWST  EQU 8
ZF_WRST  EQU 16
ZF_SKST  EQU 32

ZP_RDIN:
LD A,(ZS_FAIL)
AND ZF_RIN
JR NZ,ZP_INER
LD A,(ZS_IPOS)
LD C,A
LD A,(ZS_ILEN)
CP C
JP Z,ZP_EOF
JR C,ZP_INER
LD B,0
LD HL,ZS_IBUF
ADD HL,BC
LD A,C
INC A
LD (ZS_IPOS),A
LD A,(HL)
OR A
RET
ZP_INER:
LD A,ZS_INERR
SCF
RET

ZP_WOUT:
LD E,A
LD A,(ZS_FAIL)
AND ZF_WOUT
JR NZ,ZP_OUTER
LD A,(ZS_OLEN)
LD C,A
LD A,(ZS_OCAP)
CP C
JR Z,ZP_OUTER
JR C,ZP_OUTER
LD B,0
LD HL,ZS_OBUF
ADD HL,BC
LD (HL),E
LD A,C
INC A
LD (ZS_OLEN),A
XOR A
RET
ZP_OUTER:
LD A,ZS_OUTER
SCF
RET

ZP_RDST:
LD A,(ZS_FAIL)
AND ZF_RST
JR NZ,ZP_STERR
LD A,(ZS_SIPOS)
LD C,A
LD A,(ZS_SILEN)
CP C
JP Z,ZP_EOF
JP C,ZP_STERR
LD B,0
LD HL,ZS_SIBUF
ADD HL,BC
LD A,C
INC A
LD (ZS_SIPOS),A
LD A,(HL)
OR A
RET

ZP_RWST:
LD A,(ZS_FAIL)
AND ZF_RWST
JP NZ,ZP_STERR
XOR A
LD (ZS_SIPOS),A
RET

ZP_WRST:
LD E,A
LD A,(ZS_FAIL)
AND ZF_WRST
JP NZ,ZP_STERR
LD A,(ZS_SOPOS)
LD C,A
LD A,(ZS_SOLEN)
CP C
JP C,ZP_STERR
JR NZ,ZP_SOWR
LD A,(ZS_SOCAP)
CP C
JP Z,ZP_STERR
JP C,ZP_STERR
LD A,C
INC A
LD (ZS_SOLEN),A
ZP_SOWR:
LD B,0
LD HL,ZS_SOBUF
ADD HL,BC
LD (HL),E
LD A,C
INC A
LD (ZS_SOPOS),A
XOR A
RET

ZP_SKST:
LD A,(ZS_FAIL)
AND ZF_SKST
JP NZ,ZP_STERR
LD A,H
OR A
JP NZ,ZP_STERR
LD A,(ZS_SOLEN)
CP L
JP C,ZP_STERR
LD A,L
LD (ZS_SOPOS),A
XOR A
RET

ZP_EOF:
LD A,ZS_EOF
SCF
RET
ZP_STERR:
LD A,ZS_STERR
SCF
RET
ZS_PCEND:

ZS_FAIL: DB 0
ZS_IPOS: DB 0
ZS_ILEN: DB 0
ZS_IBUF: DS ZS_CAP
ZS_OLEN: DB 0
ZS_OCAP: DB 0
ZS_OBUF: DS ZS_CAP
ZS_SIPOS: DB 0
ZS_SILEN: DB 0
ZS_SIBUF: DS ZS_CAP
ZS_SOPOS: DB 0
ZS_SOLEN: DB 0
ZS_SOCAP: DB 0
ZS_SOBUF: DS ZS_CAP
ZS_MEND:
ZS_PEND:
